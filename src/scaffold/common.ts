import type { Project } from '../types';
import type { BoardSpec, FamilyId, ScaffoldFile } from './types';

/* ============================================================
 *  base 계층 — 모든 프로젝트가 공유하는 공통 파일
 *  board.h / 호스트 시뮬 스텁 / README / .gitignore / in-project CI
 * ============================================================ */

const BOARD_H = String.raw`#ifndef BOARD_H
#define BOARD_H

#include <stdint.h>

/* 보드 추상화 — 호스트(sim) / 타깃(ARM) 양쪽에서 동일하게 컴파일된다. */
void     board_init(void);
uint32_t board_millis(void);
void     board_delay_ms(uint32_t ms);
void     board_led_toggle(void);
void     board_log(const char *msg);

#endif /* BOARD_H */
`;

const BOARD_SIM_C = String.raw`/* board_sim.c — 호스트 시뮬레이션용 board_* 구현 (BOARD_HOST_SIM) */
#include "board.h"
#include <stdio.h>

static uint32_t g_ms;

void board_init(void)
{
    g_ms = 0u;
}

uint32_t board_millis(void)
{
    return g_ms;
}

void board_delay_ms(uint32_t ms)
{
    g_ms += ms;
}

void board_led_toggle(void)
{
    /* host: no-op */
}

void board_log(const char *msg)
{
    printf("[sim] %s\n", msg);
}
`;

function readme(p: Project, board: BoardSpec, family: FamilyId): string {
  const goals = p.goals.map((g) => `- ${g}`).join('\n');
  const isHost = board.isHost;
  const buildSection = isHost
    ? String.raw`### 네이티브(POSIX) 빌드
    make              # build/${p.id}
    make run          # 실행
    make test         # 알고리즘 자체 테스트`
    : String.raw`### 1) 호스트 시뮬레이션 (하드웨어 불필요)
    make sim
    make run          # [sim] ... / self-test done

### 2) 타깃(ARM) 펌웨어
    make arm          # build/${p.id}.elf  (arm-none-eabi-gcc 필요)

### 3) 알고리즘 자체 테스트
    make test`;

  const dirs = isHost
    ? String.raw`- ` + '`src/`' + ` 애플리케이션 진입점(main)
- ` + '`app/`' + ` 모듈 로직
- ` + '`include/`' + ` 공용 헤더
- ` + '`tests/`' + ` 알고리즘 자체 테스트 (make test)`
    : String.raw`- ` + '`src/`' + ` 애플리케이션 진입점(main)
- ` + '`drivers/`' + ` 하드웨어 드라이버
- ` + '`app/`' + ` 프로토콜/알고리즘/태스크 로직
- ` + '`include/`' + ` 공용 헤더
- ` + '`sim/`' + ` 호스트 시뮬레이션 스텁
- ` + '`bsp/arm/${board.id}/`' + ` startup / 링커 / 보드 구현
- ` + '`tests/`' + ` 알고리즘 자체 테스트 (make test)`;

  return String.raw`# ${p.title} (${p.titleEn})

> ${p.code} · ${board.label} · family: \`${family}\` · generated by **AutoEmbed LAB** scaffold engine

## 개요
${p.tagline}

${p.description}

## 목표
${goals}

## 빌드

${buildSection}

## CMake (선택)
${isHost
      ? '    cmake -S . -B build/cmake && cmake --build build/cmake'
      : '    cmake -S . -B build/cmake -DCMAKE_TOOLCHAIN_FILE=cmake/arm-none-eabi.cmake && cmake --build build/cmake'}

## 디렉터리
${dirs}
`;
}

const GITIGNORE = String.raw`build/
cmake-build-*/
*.o
*.elf
*.bin
*.hex
*.map
*.d
*.su
.vscode/
.idea/
`;

function inProjectCi(board: BoardSpec): string {
  if (board.isHost) {
    return String.raw`name: build

on:
  push:
  pull_request:

jobs:
  native:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Build
        run: make CC=cc
      - name: Run
        run: make run CC=cc
      - name: Test
        run: make test CC=cc
`;
  }
  return String.raw`name: build

on:
  push:
  pull_request:

jobs:
  host-sim:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Build host simulation
        run: make sim CC=cc
      - name: Run host simulation
        run: ./build/sim
      - name: Run algorithm tests
        run: make test CC=cc

  arm-target:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: carlosperate/arm-none-eabi-gcc-action@v1
      - name: Build ARM firmware
        run: make arm
      - name: Build via CMake
        run: cmake -S . -B build/cmake -DCMAKE_TOOLCHAIN_FILE=cmake/arm-none-eabi.cmake && cmake --build build/cmake
`;
}

export function commonFiles(p: Project, board: BoardSpec, family: FamilyId): ScaffoldFile[] {
  const files: ScaffoldFile[] = [
    { path: 'README.md', content: readme(p, board, family) },
    { path: '.gitignore', content: GITIGNORE },
    { path: '.github/workflows/build.yml', content: inProjectCi(board) },
  ];
  if (!board.isHost) {
    files.push({ path: 'include/board.h', content: BOARD_H });
    files.push({ path: 'sim/board_sim.c', content: BOARD_SIM_C });
    files.push({ path: `bsp/arm/${board.id}/${board.startupName}`, content: board.startup });
    files.push({ path: `bsp/arm/${board.id}/${board.ldName}`, content: board.ld });
    files.push({ path: `bsp/arm/${board.id}/${board.boardCName}`, content: board.boardC });
    files.push({ path: `bsp/arm/${board.id}/${board.systemCName}`, content: board.systemC });
  }
  return files;
}
