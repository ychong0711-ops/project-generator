import type { Project } from '../types';
import type { BoardSpec, BuildSystem, FamilyId, ScaffoldFile } from './types';

/* ============================================================
 *  빌드시스템 생성 — Makefile(1차) + CMake(2차)
 *  라인 배열로 조립하여 `$` / `${...}` 이스케이프 문제를 회피한다.
 * ============================================================ */

const TAB = '\t';
const J = (lines: string[]) => lines.join('\n') + '\n';

function makefile(p: Project, board: BoardSpec, family: FamilyId): string {
  const host = board.isHost ? '1' : '0';
  const lines: string[] = [
    `# ${p.id} — generated by AutoEmbed LAB`,
    `PROJECT := ${p.id}`,
    `BOARD   := ${board.id}`,
    `FAMILY  := ${family}`,
    `HOST    := ${host}`,
    '',
    'ifeq ($(OS),Windows_NT)',
    '  EXE := .exe',
    'else',
    '  EXE :=',
    'endif',
    '',
    'BUILD    := build',
    'INCLUDES := -Iinclude',
    'CFLAGS   := -std=c11 -Wall -Wextra -O2 $(INCLUDES)',
    'SRCS     := $(wildcard src/*.c app/*.c drivers/*.c lib/*.c)',
    'CC       ?= cc',
    '',
    'ifeq ($(HOST),1)',
    '',
    'BIN := $(BUILD)/$(PROJECT)$(EXE)',
    '',
    'all: $(BIN)',
    'sim: $(BIN)',
    '',
    '$(BIN): $(SRCS)',
    TAB + '@mkdir -p $(BUILD)',
    TAB + '$(CC) $(CFLAGS) $(SRCS) -o $@',
    '',
    'arm:',
    TAB + '@echo "$(PROJECT): host target — no ARM build"',
    '',
    'else',
    '',
    'SIM_BIN    := $(BUILD)/sim$(EXE)',
    'SIM_SRCS   := $(SRCS) sim/board_sim.c',
    'SIM_CFLAGS := $(CFLAGS) -DBOARD_HOST_SIM -g',
    '',
    'PREFIX     ?= arm-none-eabi-',
    'CROSS_CC   := $(PREFIX)gcc',
    `CPU        := ${board.cpu}`,
    `DEFS       := -D${board.mcuDefine}`,
    'ARM_CFLAGS := -mcpu=$(CPU) -mthumb $(CFLAGS) $(DEFS) -ffreestanding -fno-builtin',
    'ARM_SRCS   := $(SRCS) $(wildcard bsp/arm/$(BOARD)/*.c)',
    `ARM_ASM    := bsp/arm/$(BOARD)/${board.startupName}`,
    `LDSCRIPT   := bsp/arm/$(BOARD)/${board.ldName}`,
    'ARM_ELF    := $(BUILD)/$(PROJECT).elf',
    '',
    'all: arm',
    'arm: $(ARM_ELF)',
    'sim: $(SIM_BIN)',
    '',
    '$(SIM_BIN): $(SIM_SRCS)',
    TAB + '@mkdir -p $(BUILD)',
    TAB + '$(CC) $(SIM_CFLAGS) $(SIM_SRCS) -o $@',
    '',
    '$(ARM_ELF): $(ARM_SRCS) $(ARM_ASM) $(LDSCRIPT)',
    TAB + '@mkdir -p $(BUILD)',
    TAB + '$(CROSS_CC) $(ARM_CFLAGS) -T $(LDSCRIPT) -nostartfiles -Wl,--gc-sections \\',
    TAB + '\t-Wl,-Map=$(BUILD)/$(PROJECT).map $(ARM_SRCS) $(ARM_ASM) -o $@',
    '',
    'endif',
    '',
    'run: sim',
    '\t@if [ "$(HOST)" = "1" ]; then ./$(BUILD)/$(PROJECT)$(EXE); else ./$(BUILD)/sim$(EXE); fi',
    '',
    'TESTS := $(patsubst tests/%.c,$(BUILD)/test_%$(EXE),$(wildcard tests/*.c))',
    '',
    '$(BUILD)/test_%$(EXE): tests/%.c',
    TAB + '@mkdir -p $(BUILD)',
    TAB + '$(CC) $(CFLAGS) $< -o $@',
    '',
    'test: $(TESTS)',
    TAB +
      '@pass=0; fail=0; for t in $(TESTS); do echo "== $$t =="; if ./$$t >/dev/null 2>&1; then pass=$$((pass+1)); else fail=$$((fail+1)); echo "FAIL: $$t"; fi; done; echo "tests: pass=$$pass fail=$$fail"; test $$fail -eq 0',
    '',
    'clean:',
    TAB + 'rm -rf $(BUILD)',
    '',
    '.PHONY: all arm sim run test clean',
  ];
  return J(lines);
}

function cmakeLists(p: Project, board: BoardSpec): string {
  const common = [
    'cmake_minimum_required(VERSION 3.20)',
    board.isHost ? `project(${p.id} C)` : `project(${p.id} C ASM)`,
    'set(CMAKE_C_STANDARD 11)',
    'set(CMAKE_C_STANDARD_REQUIRED ON)',
  ];
  if (board.isHost) {
    return J([
      ...common,
      'add_compile_options(-Wall -Wextra -O2)',
      'file(GLOB SRC src/*.c app/*.c drivers/*.c lib/*.c)',
      'add_executable(${PROJECT_NAME} ${SRC})',
      'target_include_directories(${PROJECT_NAME} PRIVATE include)',
    ]);
  }
  return J([
    ...common,
    `add_compile_options(-mcpu=${board.cpu} -mthumb -Wall -Wextra -O2 -ffreestanding -fno-builtin -D${board.mcuDefine})`,
    `file(GLOB SRC src/*.c app/*.c drivers/*.c lib/*.c bsp/arm/${board.id}/*.c)`,
    `set(LD  bsp/arm/${board.id}/${board.ldName})`,
    `set(STARTUP bsp/arm/${board.id}/${board.startupName})`,
    'add_executable(${PROJECT_NAME} ${SRC} ${STARTUP})',
    'target_include_directories(${PROJECT_NAME} PRIVATE include)',
    'target_link_options(${PROJECT_NAME} PRIVATE -T ${CMAKE_SOURCE_DIR}/${LD} -nostartfiles -Wl,--gc-sections)',
  ]);
}

const ARM_TOOLCHAIN = J([
  '# arm-none-eabi 툴체인 파일 (CMake)',
  'set(CMAKE_SYSTEM_NAME Generic)',
  'set(CMAKE_SYSTEM_PROCESSOR arm)',
  'set(CMAKE_C_COMPILER arm-none-eabi-gcc)',
  'set(CMAKE_ASM_COMPILER arm-none-eabi-gcc)',
  'set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)',
]);

export function buildSystemFiles(
  p: Project,
  board: BoardSpec,
  family: FamilyId,
  systems: BuildSystem[]
): ScaffoldFile[] {
  const files: ScaffoldFile[] = [];
  if (systems.includes('make')) {
    files.push({ path: 'Makefile', content: makefile(p, board, family) });
  }
  if (systems.includes('cmake')) {
    files.push({ path: 'CMakeLists.txt', content: cmakeLists(p, board) });
    if (!board.isHost) {
      files.push({ path: 'cmake/arm-none-eabi.cmake', content: ARM_TOOLCHAIN });
    }
  }
  return files;
}
